// Reading, merging and writing the generated manifest (src/data/projectImages.ts). Pure functions, plus one
// atomic write, so the pipeline tests can run them on a temporary folder.
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';

const MANIFEST_LINE = /^\s*'([^']+)': \{ width: (\d+), height: (\d+), widths: \[([\d, ]+)\], hasShare: (true|false) \},$/;
const ENTRY_LINE_MARKER = "': {";

export function renderManifest(entries) {
  const lines = entries
    .slice()
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((entry) => `  '${entry.key}': { width: ${entry.width}, height: ${entry.height}, widths: [${entry.widths.join(', ')}], hasShare: ${entry.hasShare} },`);
  return [
    '// Generated by scripts/process-project-images.mjs. Do not edit by hand: run the script again.',
    '// width and height are the pixel size of the widest file, so the aspect ratio is known before the image loads.',
    '',
    'export interface ProjectImageEntry {',
    '  readonly width: number;',
    '  readonly height: number;',
    '  readonly widths: readonly number[];',
    '  readonly hasShare: boolean;',
    '}',
    '',
    'export const projectImageManifest: Readonly<Record<string, ProjectImageEntry>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

/**
 * The entries of a manifest text. A line that looks like an entry but does not match the expected shape (a
 * formatter, a hand edit) is an error: reading it as "no entries" would let the next run overwrite the file.
 */
export function parseManifest(text) {
  const entries = [];
  let entryLooking = 0;
  for (const line of text.split(/\r?\n/)) {
    if (line.includes(ENTRY_LINE_MARKER)) entryLooking += 1;
    const match = MANIFEST_LINE.exec(line);
    if (!match) continue;
    const widths = match[4].split(',').map((width) => Number(width.trim()));
    entries.push({ key: match[1], width: Number(match[2]), height: Number(match[3]), widths, hasShare: match[5] === 'true' });
  }
  if (entries.length !== entryLooking) {
    throw new Error(`the manifest has ${entryLooking} entry lines but only ${entries.length} could be read: it was edited or reformatted, refusing to overwrite it`);
  }
  return entries;
}

/** The entries of the manifest file on disk (none when it does not exist yet). */
export function readManifestEntries(manifestFile) {
  if (!existsSync(manifestFile)) return [];
  const text = readFileSync(manifestFile, 'utf8');
  const entries = parseManifest(text);
  if (text.trim() !== '' && entries.length === 0) throw new Error(`${manifestFile} is not empty but holds no entry: refusing to overwrite it`);
  return entries;
}

/**
 * The entries after a run: the existing ones (minus those replaced, and minus those of the cleaned slugs), then the
 * new ones. `cleanedSlugs` holds the projects of the input when --clean is on (empty otherwise).
 */
export function mergeEntries(existing, fresh, cleanedSlugs = new Set()) {
  const replaced = new Set(fresh.map((entry) => entry.key));
  const kept = existing.filter((entry) => !replaced.has(entry.key) && !cleanedSlugs.has(entry.key.split('/')[0]));
  return [...kept, ...fresh];
}

/** Writes through a temporary file and a rename, so a crash never leaves a half written file. */
export function writeFileAtomic(file, content) {
  const temporary = `${file}.${process.pid}.tmp`;
  try {
    writeFileSync(temporary, content, 'utf8');
    renameSync(temporary, file);
  } finally {
    rmSync(temporary, { force: true });
  }
}
